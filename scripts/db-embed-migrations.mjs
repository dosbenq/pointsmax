#!/usr/bin/env node
// Embed db/migrations/*.sql into src/lib/db/migrations.generated.ts so the
// deployed app can apply them itself (serverless bundles don't reliably
// include loose .sql files). Run by `npm run db:generate`; a unit test fails
// if the embedded copy drifts from the SQL files.
import { createHash } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'

const ROOT = process.cwd()
const MIGRATIONS_DIR = path.join(ROOT, 'db', 'migrations')
const OUTPUT = path.join(ROOT, 'src', 'lib', 'db', 'migrations.generated.ts')

export function readMigrations(dir = MIGRATIONS_DIR) {
  const journal = JSON.parse(fs.readFileSync(path.join(dir, 'meta', '_journal.json'), 'utf8'))
  return journal.entries.map((entry) => {
    const source = fs.readFileSync(path.join(dir, `${entry.tag}.sql`), 'utf8')
    return {
      tag: entry.tag,
      hash: createHash('sha256').update(source).digest('hex'),
      statements: source
        .split('--> statement-breakpoint')
        .map((statement) => statement.trim())
        .filter(Boolean),
    }
  })
}

export function renderModule(migrations) {
  return [
    '// Generated by scripts/db-embed-migrations.mjs from db/migrations. Do not edit.',
    '// Regenerate with `npm run db:generate`.',
    '',
    'export type EmbeddedMigration = { tag: string; hash: string; statements: string[] }',
    '',
    `export const MIGRATIONS: EmbeddedMigration[] = ${JSON.stringify(migrations, null, 2)}`,
    '',
  ].join('\n')
}

if (import.meta.url === `file://${process.argv[1]}`) {
  fs.writeFileSync(OUTPUT, renderModule(readMigrations()))
  console.log(`Embedded migrations into ${path.relative(ROOT, OUTPUT)}`)
}
